// @ts-check
// Renders docs/config.md from the JSON Schema of agent-qa.yaml (npm run schema writes
// it; a test checks the committed file matches). Every key's text is the `.describe()`
// in src/core/config/schema.ts, so the reference and the IDE hover can't drift apart.

const SECRET = "^\\$\\{(env|keychain):([A-Za-z_][A-Za-z0-9_.-]*)\\}$";

/** @param {any} n @returns {string} */
function typeOf(n) {
  if (!n || typeof n !== "object") return "any";
  if (n.anyOf) return n.anyOf.map(typeOf).join(" or ");
  if (n.const !== undefined) return `\`${JSON.stringify(n.const)}\``;
  if (n.enum) return n.enum.map((v) => `\`${v}\``).join(", ");
  if (n.type === "null") return "null";
  if (n.type === "string") {
    if (n.pattern === SECRET) return "secret reference";
    if (n.format === "uri") return "URL";
    return "text";
  }
  if (n.type === "integer") {
    const range = n.minimum !== undefined && n.maximum !== undefined ? ` (${n.minimum} to ${n.maximum})` : "";
    return `whole number${range}`;
  }
  if (n.type === "number") return "number";
  if (n.type === "boolean") return "true or false";
  if (n.type === "array") return n.items?.anyOf?.length > 1 ? "list" : `list of ${typeOf(n.items)}`;
  if (n.type === "object") {
    if (n.properties) return "section";
    if (n.additionalProperties && typeof n.additionalProperties === "object") {
      const keys = n.propertyNames?.enum ? ` (${n.propertyNames.enum.map((v) => `\`${v}\``).join(", ")})` : "";
      return `map of name${keys} to ${typeOf(n.additionalProperties)}`;
    }
    return "section";
  }
  return "any";
}

/** @param {any} n */
function defaultOf(n, required) {
  if (n.default !== undefined) {
    const d = n.default;
    return typeof d === "object" ? "see its keys" : `\`${String(d)}\``;
  }
  return required ? "required" : "";
}

/** @param {string} text */
const cell = (text) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

/**
 * The rows of one section: every key below it, as a dotted path, in schema order.
 * @param {any} node @param {string} path @param {string[]} rows
 */
function rowsOf(node, path, rows, alternatives = false) {
  const objects = node.anyOf ? node.anyOf.filter((x) => x.type === "object") : [node];
  for (const obj of objects) {
    const required = new Set(obj.required ?? []);
    for (const [key, child] of Object.entries(obj.properties ?? {})) {
      const p = `${path}.${key}`;
      const dflt = alternatives ? "one of these" : defaultOf(child, required.has(key));
      rows.push(`| \`${p}\` | ${cell(typeOf(child))} | ${dflt} | ${cell(child.description ?? "")} |`);
      rowsOf(child, p, rows);
    }
    if (obj.type === "array" && obj.items) {
      const items = obj.items.anyOf ?? [obj.items];
      for (const item of items) rowsOf(item, `${path}[]`, rows, items.length > 1);
    }
  }
}

/** @param {any} schema the JSON Schema of agent-qa.yaml @returns {string} */
export function configReference(schema) {
  const out = [
    "# agent-qa.yaml reference",
    "",
    "<!-- Generated by `npm run schema` from src/core/config/schema.ts. Edit the descriptions there, not this file. -->",
    "",
    `${schema.description ?? ""} \`agent-qa init\` writes a starting file ([getting-started.md](getting-started.md)), and \`agent-qa doctor\` checks it. Editors that read JSON Schema (VS Code with the YAML extension) show these descriptions as you type, from the \`# yaml-language-server: $schema=…\` line at the top of the file.`,
    "",
    "A secret reference is `${env:NAME}` (an environment variable) or `${keychain:NAME}` (your OS keychain, under the service `sf-agent-qa`). A secret written in the file itself is refused.",
    "",
  ];
  const required = new Set(schema.required ?? []);
  for (const [key, node] of Object.entries(schema.properties ?? {})) {
    out.push(`## \`${key}\``, "");
    const type = typeOf(node);
    const shown = type === "section" || node.const !== undefined ? "" : ` ${type[0]?.toUpperCase()}${type.slice(1)}.`;
    out.push(`${node.description ?? ""}${shown}${required.has(key) ? " Required." : " Optional."}`, "");
    /** @type {string[]} */
    const rows = [];
    rowsOf(node, key, rows);
    if (rows.length > 0) out.push("| Key | Type | Default | What it does |", "|---|---|---|---|", ...rows, "");
  }
  return out.join("\n");
}

/**
 * Keys with no description, as dotted paths: each one must say what it does.
 * @param {any} schema @returns {string[]}
 */
export function undescribedKeys(schema) {
  /** @type {string[]} */
  const missing = [];
  /** @param {any} n @param {string} path */
  const walk = (n, path) => {
    if (!n || typeof n !== "object") return;
    for (const [k, v] of Object.entries(n.properties ?? {})) {
      const p = path ? `${path}.${k}` : k;
      if (!(/** @type {any} */ (v).description)) missing.push(p);
      walk(v, p);
    }
    for (const x of n.anyOf ?? []) walk(x, path);
    if (n.items) walk(n.items, `${path}[]`);
    if (n.additionalProperties && typeof n.additionalProperties === "object") walk(n.additionalProperties, `${path}.*`);
  };
  walk(schema, "");
  return missing;
}
