// Embeds packs/salesforce/lightning.ts in src/workflows/packs/lightning-source.ts (run: npm run packs).
// The workflow layer never reads files, so the helper file ships as text. A test checks the two match.
import { readFile, writeFile } from "node:fs/promises";

const source = await readFile(new URL("../packs/salesforce/lightning.ts", import.meta.url), "utf8");
const out = `// Generated by scripts/write-packs.mjs from packs/salesforce/lightning.ts: edit that file, then run npm run packs.\nexport const LIGHTNING_HELPERS_SOURCE = ${JSON.stringify(source.replace(/\r\n/g, "\n"))};\n`;
await writeFile(new URL("../src/workflows/packs/lightning-source.ts", import.meta.url), out);
console.log("wrote src/workflows/packs/lightning-source.ts");
